# ---------------------------------------------------------------- helpers


def canonical_bytes(obj: Any) -> bytes:
    return (json.dumps(obj, sort_keys=True, separators=(",", ":")) + "\n").encode("utf-8")


def sha256_bytes(payload: bytes) -> str:
    return hashlib.sha256(payload).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def ensure_repo(repo_root: Path) -> None:
    for entry in (str(repo_root), str(repo_root / "scripts")):
        if entry not in sys.path:
            sys.path.insert(0, entry)


def enforce_freeze_pins(repo_root: Path) -> None:
    """Hard-fail on any drift vs the executed D0 freeze (checker defect 4)."""

    for rel, expected in FREEZE_FILE_PINS.items():
        path = repo_root / rel
        if not path.is_file():
            raise SystemExit(f"freeze-pin file missing: {rel}")
        actual = sha256_file(path)
        if actual != expected:
            raise SystemExit(
                f"freeze-pin mismatch: {rel}\n  expected {expected}\n  actual   {actual}\n"
                "checkout drifted from the frozen D0 state -- refusing to generate"
            )
    probe = subprocess.run(
        ["git", "-C", str(repo_root), "merge-base", "--is-ancestor", FREEZE_COMMIT, "HEAD"],
        capture_output=True,
    )
    if probe.returncode != 0:
        head = git_head(repo_root)
        raise SystemExit(
            f"checkout HEAD {head} does not descend from the freeze commit {FREEZE_COMMIT} "
            "-- refusing to generate"
        )
    anchor_path = repo_root / A2_BUNDLE_REL
    if anchor_path.is_file():
        actual = sha256_file(anchor_path)
        if actual != A2_BUNDLE_ANCHOR:
            raise SystemExit(
                f"A-2 bundle anchor mismatch: {A2_BUNDLE_REL}\n  expected {A2_BUNDLE_ANCHOR}\n"
                f"  actual   {actual}"
            )


