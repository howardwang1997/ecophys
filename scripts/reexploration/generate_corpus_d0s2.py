def stream_dir(out_dir: Path, family: str, axis: str, kernel: str, seed_root: int) -> Path:
    return out_dir / family / f"axis_{axis}" / f"kernel_{kernel}" / f"seed_{seed_root:06d}"


def episode_dir(sdir: Path, episode_index: int) -> Path:
    return sdir / f"episode_{episode_index:04d}"


def git_head(repo_root: Path) -> str | None:
    try:
        return subprocess.run(
            ["git", "-C", str(repo_root), "rev-parse", "HEAD"],
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
    except Exception:
        return None


def fexec_payload(corpus: Any) -> dict[str, Any]:
    """JSON form of an E-1 FexecCorpus (tensors via tolist; float repr is
    CPython-shortest and stable across nodes for identical doubles)."""

    return {
        "session_id": corpus.session_id,
        "allocation_rule": corpus.allocation_rule,
        "seed": corpus.seed,
        "n_slots": corpus.n_slots,
        "dtype": str(corpus.features.dtype),
        "match_ticks": list(corpus.match_ticks),
        "n_executions": corpus.n_executions,
        "features": corpus.features.tolist(),
        "channels_delta": corpus.channels_delta.tolist(),
        "channels_cumulative": corpus.channels_cumulative.tolist(),
        "slot_prices": corpus.slot_prices.tolist(),
        "slot_quantities": corpus.slot_quantities.tolist(),
        "tape_hash": corpus.tape_hash,
        "content_hash": corpus.content_hash,
        "corpus_hash": corpus.corpus_hash,
    }


# ---------------------------------------------------------------- generation


def generate_episode_artifacts(surface: dict[str, Any], job: dict[str, Any],
                               episode_index: int) -> dict[str, Any]:
    dgp = surface["dgp"]
    seed_root = job["seed_root"]
    cfg = dgp.config_for_axis(dgp.config_from_mapping(job["config"]), job["axis"])
    stream = dgp.generate_episode(seed_root, episode_index, cfg)
    episode_sha = sha256_bytes(dgp.episode_canonical_json(stream))
    draw_seed = dgp.derive_seed(seed_root, DRAW_SEED_TAG, episode_index)
    prestate = dgp.build_prestate(stream, surface["AllocationRule"](job["kernel"]), draw_seed)

    engine = surface["ReferenceEngine"](prestate)
    for request in dgp.order_requests(stream):
        engine.submit(request)
    engine.finish()
    tape = engine.tape

    # E-4 (replay guard enforced inside emit_conserving_channels)
    series = surface["emit_conserving_channels"](prestate, tape)
    violations = surface["conservation_violations"](series)
    settlement = surface["settlement_violations"](prestate, tape, series)
    if violations or settlement:
        raise RuntimeError(
            f"conservation/settlement gate failed (F2 sec.8.3 instrument) "
            f"seed_root={seed_root} episode={episode_index}: {violations + settlement}"
        )

    # E-1 + cross-item grid agreement (cheap per-session assert, E-1/E-4 contract)
    corpus = surface["project_fexec_corpus"](prestate, tape, seed_root)
    if corpus.channels_delta.tolist() != series.increment_matrix():
        raise RuntimeError(
            f"E-1/E-4 round-grid disagreement seed_root={seed_root} "
            f"episode={episode_index}"
        )

    edir = episode_dir(
        stream_dir(Path(job["out_dir"]), job["family"], job["axis"], job["kernel"], seed_root),
        episode_index,
    )
    edir.mkdir(parents=True, exist_ok=True)
    blobs = {
        "prestate.json": (surface["prestate_to_json"](prestate) + "\n").encode("utf-8"),
        "tape.jsonl": "".join(
            surface["record_to_json"](record) + "\n" for record in tape
        ).encode("utf-8"),
        "channels.json": (series.to_json() + "\n").encode("utf-8"),
        "fexec_corpus.json": canonical_bytes(fexec_payload(corpus)),
    }
    files = {}
    for name, blob in blobs.items():
        (edir / name).write_bytes(blob)
        files[name] = sha256_bytes(blob)
    return {
        "episode_index": episode_index,
        "draw_seed": draw_seed,
        "session_id": prestate.session_id,
        "prestate_hash": tape[0].payload["prestate_hash"],
        "episode_canonical_json_sha256": episode_sha,
        "config_fingerprint": dgp.config_fingerprint(cfg),
        "files": files,
        "n_records": len(tape),
        "n_rounds": len(corpus.rounds),
        "n_executions": corpus.n_executions,
        "tape_hash": corpus.tape_hash,
        "content_hash": corpus.content_hash,
        "corpus_hash": corpus.corpus_hash,
        "conservation_violations": len(violations),
        "settlement_violations": len(settlement),
        "e1_e4_grid_match": True,
    }


def entry_files_verify(edir: Path, entry: dict[str, Any]) -> bool:
    for name, expected in sorted(entry["files"].items()):
        path = edir / name
        if not path.is_file() or sha256_file(path) != expected:
            return False
    return True


def process_stream(job: dict[str, Any]) -> dict[str, Any]:
    """One seed root = one embarrassingly parallel stream (unit of work)."""

    surface = load_surface(Path(job["repo_root"]))
    out_dir = Path(job["out_dir"])
    sdir = stream_dir(out_dir, job["family"], job["axis"], job["kernel"], job["seed_root"])
    previous: dict[int, dict[str, Any]] = {}
    prev_path = sdir / "stream_manifest.json"
    if prev_path.is_file():
        previous = {
            int(e["episode_index"]): e
            for e in json.loads(prev_path.read_text())["episodes"]
        }

    entries: list[dict[str, Any]] = []
    for episode_index in range(job["episodes"]):
        prior = previous.get(episode_index)
        edir = episode_dir(sdir, episode_index)
        if prior is not None and entry_files_verify(edir, prior):
            entries.append(prior)  # F1 sec.4: completed episodes never regenerate
            continue
        if job["manifest_only"]:
            raise RuntimeError(
                f"manifest-only: missing or unverified artifacts for {edir}; "
                "run generation first"
            )
        entry = generate_episode_artifacts(surface, job, episode_index)
        if prior is not None and entry["files"] != prior["files"]:
            # F1 sec.4 halt: regenerated bytes differ from the frozen stream
            # manifest -- nondeterminism or tampering, never silently relaundered.
            raise RuntimeError(
                f"{edir}: regenerated bytes differ from the frozen stream "
                "manifest (F1 sec.4 halt)"
            )
        entries.append(entry)

    manifest = {
        "schema_version": STREAM_MANIFEST_SCHEMA,
        "campaign_id": CAMPAIGN_ID,
        "stage": "D0-S2",
        "seed_root": job["seed_root"],
        "namespace": job["namespace"],
        "family": job["family"],
        "axis": job["axis"],
        "kernel": job["kernel"],
        "dgp_config_fingerprint": job["config_fingerprint"],
        "episodes_per_seed": job["episodes"],
        "draw_seed_rule": f'derive_seed(seed_root, "{DRAW_SEED_TAG}", episode_index)',
        "episodes": entries,
    }
    sdir.mkdir(parents=True, exist_ok=True)
    manifest_path = sdir / "stream_manifest.json"
    manifest_path.write_bytes(canonical_bytes(manifest))
    return {
        "seed_root": job["seed_root"],
        "namespace": job["namespace"],
        "n_episodes": len(entries),
        "n_records": sum(e["n_records"] for e in entries),
        "n_rounds": sum(e["n_rounds"] for e in entries),
        "n_executions": sum(e["n_executions"] for e in entries),
        "manifest": manifest_path.relative_to(out_dir).as_posix(),
        "manifest_sha256": sha256_file(manifest_path),
    }


# ---------------------------------------------------------------- validation


def boundary_aggregate_hashes(tape_path: Path) -> list[str] | None:
    """post_aggregate_state_hash sequence at order_accepted boundaries
    (F3 sec.2.6 item 3 dual-arm CRN surface); None when unreadable."""

    values: list[str] = []
    for line in tape_path.read_text().splitlines():
        if not line.strip():
            continue
        raw = json.loads(line)
        if raw.get("event_type") == "order_accepted":
            values.append(raw.get("post_aggregate_state_hash", ""))
    return values


def validate_stream(job: dict[str, Any]) -> dict[str, Any]:
    """Byte-exact re-derivation + replay validation (F1 sec.3 item 2, F3 2.6).

    Per episode: (i) re-derive the episode and compare episode_canonical_json
    sha256; (ii) re-derive prestate and compare prestate.json bytes; (iii)
    re-execute the engine and compare tape.jsonl bytes; (iv) re-run E-4/E-1
    and compare channels.json / fexec_corpus.json bytes; (v) replay-validate
    the DISK prestate/tape via lab_asset.replay.replay (record-by-record incl.
    all four hashes); (vi) re-verify every artifact sha256 against the stream
    manifest entry. Cross-arm: when the sibling kernel tree exists, assert
    stream identity and the order_accepted aggregate-hash CRN sequence.
    """

    surface = load_surface(Path(job["repo_root"]))
    dgp = surface["dgp"]
    seed_root = job["seed_root"]
    sdir = stream_dir(Path(job["out_dir"]), job["family"], job["axis"], job["kernel"], seed_root)
    failures: list[str] = []
    manifest_path = sdir / "stream_manifest.json"
    if not manifest_path.is_file():
        return {"seed_root": seed_root, "n_episodes": 0,
                "failures": [f"missing {manifest_path}"]}
    manifest = json.loads(manifest_path.read_text())
    for key in ("kernel", "axis", "family"):
        if manifest[key] != job[key]:
            failures.append(f"stream manifest {key}={manifest[key]} != cli {job[key]}")
    if manifest["dgp_config_fingerprint"] != job["config_fingerprint"]:
        failures.append("stream manifest dgp_config_fingerprint != cli config fingerprint")
    if manifest["episodes_per_seed"] != job["episodes"]:
        failures.append(
            f"stream manifest episodes_per_seed={manifest['episodes_per_seed']} "
            f"!= cli {job['episodes']} (a wrong --episodes-per-seed silently "
            "validates a subset)"
        )
    cfg = dgp.config_for_axis(dgp.config_from_mapping(job["config"]), job["axis"])

    sibling_kernel = (
        "random_unit_within_price" if job["kernel"] == "fifo" else "fifo"
    )
    sibling_dir = stream_dir(
        Path(job["out_dir"]), job["family"], job["axis"], sibling_kernel, seed_root
    )

    for entry in manifest["episodes"]:
        episode_index = int(entry["episode_index"])
        edir = episode_dir(sdir, episode_index)
        label = f"seed_root={seed_root} episode={episode_index}"
        for name, expected in sorted(entry["files"].items()):
            path = edir / name
            if not path.is_file() or sha256_file(path) != expected:
                failures.append(f"{label}: artifact hash mismatch {name}")

        stream = dgp.generate_episode(seed_root, episode_index, cfg)
        if sha256_bytes(dgp.episode_canonical_json(stream)) != entry["episode_canonical_json_sha256"]:
            failures.append(f"{label}: episode_canonical_json re-derivation mismatch")
            continue
        prestate = dgp.build_prestate(
            stream, surface["AllocationRule"](manifest["kernel"]), entry["draw_seed"]
        )
        expected_prestate = (surface["prestate_to_json"](prestate) + "\n").encode("utf-8")
        if not (edir / "prestate.json").is_file() or (edir / "prestate.json").read_bytes() != expected_prestate:
            failures.append(f"{label}: prestate re-derivation mismatch")

        engine = surface["ReferenceEngine"](prestate)
        for request in dgp.order_requests(stream):
            engine.submit(request)
        engine.finish()
        regenerated = "".join(
            surface["record_to_json"](record) + "\n" for record in engine.tape
        ).encode("utf-8")
        if not (edir / "tape.jsonl").is_file() or (edir / "tape.jsonl").read_bytes() != regenerated:
            failures.append(f"{label}: tape re-derivation mismatch")

        series = surface["emit_conserving_channels"](prestate, engine.tape)
        expected_channels = (series.to_json() + "\n").encode("utf-8")
        if not (edir / "channels.json").is_file() or (edir / "channels.json").read_bytes() != expected_channels:
            failures.append(f"{label}: channels re-derivation mismatch")
        corpus = surface["project_fexec_corpus"](prestate, engine.tape, seed_root)
        expected_fexec = canonical_bytes(fexec_payload(corpus))
        if not (edir / "fexec_corpus.json").is_file() or (edir / "fexec_corpus.json").read_bytes() != expected_fexec:
            failures.append(f"{label}: fexec_corpus re-derivation mismatch")

        disk_prestate = surface["prestate_from_json"]((edir / "prestate.json").read_text())
        disk_tape = surface["load_tape"](edir / "tape.jsonl")
        report = surface["replay"](disk_prestate, disk_tape)
        if not report.ok:
            failures.append(
                f"{label}: replay FAILED at sequence {report.first_mismatch_sequence}"
            )

        # F3 sec.2.6 item 3: dual-arm CRN across kernels on the same request stream
        sibling_tape = episode_dir(sibling_dir, episode_index) / "tape.jsonl"
        sibling_manifest = sibling_dir / "stream_manifest.json"
        if sibling_tape.is_file() and sibling_manifest.is_file():
            sibling_entries = {
                int(e["episode_index"]): e
                for e in json.loads(sibling_manifest.read_text())["episodes"]
            }
            sibling_entry = sibling_entries.get(episode_index)
            if sibling_entry is None:
                failures.append(f"{label}: sibling kernel tree missing episode entry")
            else:
                if sibling_entry["episode_canonical_json_sha256"] != entry["episode_canonical_json_sha256"]:
                    failures.append(f"{label}: sibling kernel stream identity broken")
                mine = boundary_aggregate_hashes(edir / "tape.jsonl")
                theirs = boundary_aggregate_hashes(sibling_tape)
                if not mine or not theirs:
                    failures.append(
                        f"{label}: CRN check found no order_accepted boundaries "
                        "(boundary extraction broken)"
                    )
                elif mine != theirs:
                    failures.append(
                        f"{label}: dual-arm CRN violation -- post_aggregate_state_hash "
                        "sequence diverges across kernels at order_accepted boundaries"
                    )
    return {"seed_root": seed_root, "n_episodes": len(manifest["episodes"]),
            "failures": failures}


