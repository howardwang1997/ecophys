def parse_seed_range(text: str) -> range:
    start_text, stop_text = text.split(":")
    start, stop = int(start_text), int(stop_text)
    if stop <= start:
        raise argparse.ArgumentTypeError("seed range must be start < stop (half-open)")
    return range(start, stop)


def run_pool(jobs: list[dict[str, Any]], workers: int, fn) -> tuple[list[dict[str, Any]], list[str]]:
    results: list[dict[str, Any]] = []
    failures: list[str] = []
    if workers <= 1:
        for job in jobs:
            try:
                results.append(fn(job))
                print(f"stream seed_root={job['seed_root']}: done", flush=True)
            except Exception:
                failures.append(f"seed_root={job['seed_root']}\n{traceback.format_exc()}")
        return results, failures
    with ProcessPoolExecutor(max_workers=workers) as pool:
        futures = {pool.submit(fn, job): job["seed_root"] for job in jobs}
        for future in as_completed(futures):
            seed_root = futures[future]
            try:
                results.append(future.result())
                print(f"stream seed_root={seed_root}: done", flush=True)
            except Exception:
                failures.append(f"seed_root={seed_root}\n{traceback.format_exc()}")
    return results, failures


