"""Versioned schema for the controlled-market truth asset (A-2 mechanism kernel).

Both arms use the same record grammar.  The treatment is strict FIFO versus uniform
sampling of *resting units* at the execution price.  Unit sampling is deliberate: an
actor cannot improve allocation probability merely by splitting one quantity across
several child orders.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import asdict, dataclass, field
from enum import StrEnum


class Side(StrEnum):
    BID = "B"
    ASK = "S"


class AllocationRule(StrEnum):
    FIFO = "fifo"
    RANDOM_UNIT_WITHIN_PRICE = "random_unit_within_price"


