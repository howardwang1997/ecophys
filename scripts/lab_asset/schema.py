    SESSION_START = "session_start"
    LATENCY_CHOICE = "latency_choice"
    LATENCY_CHOICE_REJECTED = "latency_choice_rejected"
    ORDER_REQUEST = "order_request"
    ORDER_ACCEPTED = "order_accepted"
    ORDER_REJECTED = "order_rejected"
